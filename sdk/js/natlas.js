/**
 * natlas — a small, zero-dependency client for N-ATLAS, Nigeria's open LLM.
 *
 * Works with any OpenAI-compatible server that runs N-ATLAS (Ollama,
 * llama.cpp, vLLM, a hosted GPU). Node 18+, Deno, Bun and browsers.
 *
 *   import { Natlas } from "./natlas.js";
 *   const natlas = new Natlas();               // reads NATLAS_BASE_URL / NATLAS_MODEL / NATLAS_API_KEY
 *   const { text } = await natlas.chat("How I fit register my business?", { language: "pid" });
 *
 * What it does for you:
 *   - N-ATLAS defaults (temperature 0.1, repetition penalty 1.12 — from the model card)
 *   - "Respond in Yoruba/Hausa/Igbo/Pidgin" language hints
 *   - answers from your documents (Knowledge: keyword search, cites its sources)
 *   - keeps conversations inside the 8,092-token context window
 *   - streaming, timeouts, retries, and errors that say how to fix them
 *
 * Generated by N-ATLAS Launchpad — https://github.com/lumpyspace/N-atlas-launchpad
 */

export const VERSION = "0.1.0";

/** Facts from the N-ATLAS model card (huggingface.co/NCAIR1/N-ATLaS). */
export const NATLAS = {
  model: "NCAIR1/N-ATLaS",
  contextTokens: 8092,
  temperature: 0.1,
  repetitionPenalty: 1.12,
};

/** Language codes accepted by the `language` option. */
export const LANGUAGES = {
  en: "Nigerian-accented English",
  yo: "Yoruba",
  ha: "Hausa",
  ig: "Igbo",
  pid: "Nigerian Pidgin",
};

export const FACTS_HEADER = "Answer only from these facts. If they don't cover the question, say so:\n";

const env = (name) => (typeof process !== "undefined" && process.env ? process.env[name] : undefined);

// --- Errors -------------------------------------------------------------------

/**
 * Every failure is a NatlasError with a `code` you can switch on and a `hint`
 * that says what to do about it.
 *   code: "unreachable" | "model_missing" | "auth" | "http" | "timeout" | "aborted" | "empty" | "too_long"
 */
export class NatlasError extends Error {
  constructor(code, message, { status, hint, cause } = {}) {
    super(hint ? message + " — " + hint : message);
    this.name = "NatlasError";
    this.code = code;
    this.status = status;
    this.hint = hint;
    if (cause) this.cause = cause;
  }
}

// --- Tokens and context -------------------------------------------------------

/** Rough token count: ~4 characters per token for ASCII, fewer for accented text. */
export function estimateTokens(text) {
  if (!text) return 0;
  let ascii = 0;
  let other = 0;
  for (const ch of text) {
    if (ch.charCodeAt(0) < 128) ascii++;
    else other++;
  }
  return Math.ceil(ascii / 4 + other / 1.5);
}

/**
 * Drop the oldest turns (never the system message or the latest message) until
 * the conversation plus the reply fits the context window.
 * Returns { messages, dropped }.
 */
export function fitContext(messages, { maxTokens = 512, contextTokens = NATLAS.contextTokens } = {}) {
  const cost = (m) => estimateTokens(m.content) + 4;
  const system = messages.filter((m) => m.role === "system");
  const rest = messages.filter((m) => m.role !== "system");
  const budget = contextTokens - maxTokens;
  let total = [...system, ...rest].reduce((s, m) => s + cost(m), 0);
  let dropped = 0;
  while (total > budget && rest.length > 1) {
    total -= cost(rest.shift());
    dropped++;
  }
  if (total > budget) {
    throw new NatlasError("too_long", "The prompt is about " + total + " tokens; N-ATLAS fits " + budget + " plus the reply", {
      hint: "shorten the system prompt or the facts, or lower maxTokens",
    });
  }
  return { messages: [...system, ...rest], dropped };
}

// --- Knowledge ----------------------------------------------------------------

const STOPWORDS = new Set(
  "a an the and or but if of to in on at for from by with about as is are was were be been being do does did have has had i you he she it we they me my your our their this that these those what which who whom how when where why can could will would should may might must not no yes so than then there here just also into over under up down out more most some any all each other such only own same very s t don wetin abeg dey na wey una dem e".split(" "),
);

function stem(w) {
  if (w.length > 4 && w.endsWith("s") && !w.endsWith("ss")) w = w.slice(0, -1);
  for (const suffix of ["ation", "ion", "ing", "ed", "or", "er", "ly"]) {
    if (w.endsWith(suffix) && w.length - suffix.length >= 4) return w.slice(0, -suffix.length);
  }
  return w;
}

/** Lowercase, strip accents ("kaaro" matches "káàárọ̀"), split into words, light stemming. */
export function tokenize(text) {
  return text
    .normalize("NFD")
    .replace(/\p{Mn}/gu, "")
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter((w) => w.length > 1 && !STOPWORDS.has(w))
    .map(stem);
}

/** Split text into passages of ~160 words, keeping paragraphs together. */
export function chunkText(text, { targetWords = 160, maxWords = 240 } = {}) {
  const paragraphs = text
    .replace(/\r\n?/g, "\n")
    .split(/\n\s*\n/)
    .map((p) => p.replace(/[ \t]+/g, " ").trim())
    .filter(Boolean);
  const chunks = [];
  let current = [];
  let count = 0;
  const flush = () => {
    if (current.length) chunks.push(current.join("\n\n"));
    current = [];
    count = 0;
  };
  for (const para of paragraphs) {
    const words = para.split(/\s+/).length;
    if (words > maxWords) {
      flush();
      let buf = [];
      let n = 0;
      for (const sentence of para.split(/(?<=[.!?])\s+/)) {
        const w = sentence.split(/\s+/).length;
        if (n + w > targetWords && buf.length) {
          chunks.push(buf.join(" "));
          buf = [];
          n = 0;
        }
        buf.push(sentence);
        n += w;
      }
      if (buf.length) chunks.push(buf.join(" "));
      continue;
    }
    if (count + words > targetWords && current.length) flush();
    current.push(para);
    count += words;
  }
  flush();
  return chunks;
}

/**
 * The documents your app answers from. Keyword search (BM25) — no embedding
 * model needed, works offline, and matches across English and Nigerian languages.
 *
 *   const kb = new Knowledge();
 *   kb.add("prices.txt", await readFile("prices.txt", "utf8"));
 *   await natlas.chat("How much is rice?", { knowledge: kb });
 */
export class Knowledge {
  constructor(passages = []) {
    this.passages = [];
    for (const p of passages) this.#push(p.source, p.index, p.text);
  }

  /**
   * Load passages exported by Launchpad (knowledge/passages.json) — or a
   * Launchpad project's documents ([{ name, chunks: [{ text }] }]).
   */
  static fromJSON(data) {
    const json = typeof data === "string" ? JSON.parse(data) : data;
    const kb = new Knowledge();
    for (const item of json) {
      if (Array.isArray(item.chunks)) item.chunks.forEach((c, i) => kb.#push(item.name, i + 1, c.text));
      else kb.#push(item.source, item.index, item.text);
    }
    return kb;
  }

  /** Add a document; it's split into passages. Returns the number of passages. */
  add(source, text) {
    const chunks = chunkText(text);
    chunks.forEach((t, i) => this.#push(source, i + 1, t));
    return chunks.length;
  }

  get size() {
    return this.passages.length;
  }

  #push(source, index, text) {
    this.passages.push({ source, index, text, terms: tokenize(text) });
    this.stats = undefined;
  }

  #index() {
    if (this.stats) return this.stats;
    const df = new Map();
    for (const p of this.passages) for (const t of new Set(p.terms)) df.set(t, (df.get(t) || 0) + 1);
    const avg = this.passages.reduce((s, p) => s + p.terms.length, 0) / (this.passages.length || 1) || 1;
    return (this.stats = { df, avg });
  }

  /** The k most relevant passages: [{ source, index, text, score }]. */
  search(query, k = 3) {
    const q = [...new Set(tokenize(query))];
    if (!q.length || !this.passages.length) return [];
    const { df, avg } = this.#index();
    const N = this.passages.length;
    return this.passages
      .map((p) => {
        const tf = new Map();
        for (const t of p.terms) tf.set(t, (tf.get(t) || 0) + 1);
        let score = 0;
        for (const term of q) {
          const f = tf.get(term);
          if (!f) continue;
          const n = df.get(term) || 0;
          const idf = Math.log(1 + (N - n + 0.5) / (n + 0.5));
          score += idf * ((f * 2.4) / (f + 1.4 * (0.25 + (0.75 * p.terms.length) / avg)));
        }
        return { source: p.source, index: p.index, text: p.text, score };
      })
      .filter((h) => h.score > 0)
      .sort((a, b) => b.score - a.score)
      .slice(0, k);
  }

  /** Passages as a facts block, each labelled with its source. */
  static format(hits) {
    return hits.map((h) => "[" + h.source + " — passage " + h.index + "]\n" + h.text).join("\n\n");
  }
}

// --- Language -----------------------------------------------------------------

const LANG_MARKERS = {
  yo: { chars: /[ẹọṣ]|[àáèéìíòóùú]/u, words: /(?<![\p{L}])(mo|emi|ti|naa|fun|si|lo|wa|sọ|wọn|àwọn|ilé|ọjọ́|kò|àti|tó|yìí)(?![\p{L}])/giu },
  ha: { chars: /[ɓɗƙ]/u, words: /(?<![\p{L}])(ya|ba|ne|ce|da|shi|ta|mu|su|mai|amma|don|kuma|daga|wani|kamar)(?![\p{L}])/giu },
  ig: { chars: /[ịụ]/u, words: /(?<![\p{L}])(nke|chi|gị|ha|ndi|otu|bụ|dị|ebe|ihe)(?![\p{L}])/giu },
  pid: { chars: null, words: /(?<![\p{L}])(wetin|abeg|dey|oga|wahala|sabi|una|comot|waka|chop|naim|no be|how far|na im|dem)(?![\p{L}])/giu },
};

/**
 * Best guess at the language of a reply: "en" | "yo" | "ha" | "ig" | "pid".
 * A heuristic for checking N-ATLAS answered in the language you asked for —
 * unreliable under ~10 words.
 */
export function detectLanguage(text) {
  let best = "en";
  let bestScore = 1;
  for (const [code, m] of Object.entries(LANG_MARKERS)) {
    let score = (text.match(m.words) || []).length * (code === "pid" ? 2 : 1);
    if (m.chars && m.chars.test(text)) score += 3;
    if (score > bestScore) {
      best = code;
      bestScore = score;
    }
  }
  return best;
}

// --- Client -------------------------------------------------------------------

/**
 * @typedef {{ role: "system" | "user" | "assistant", content: string }} Message
 * @typedef {{
 *   system?: string, language?: keyof LANGUAGES, knowledge?: Knowledge, k?: number,
 *   temperature?: number, maxTokens?: number, repetitionPenalty?: number | null,
 *   stop?: string[], signal?: AbortSignal, timeoutMs?: number,
 * }} ChatOptions
 * @typedef {{
 *   text: string, model: string, latencyMs: number,
 *   usage?: { promptTokens: number, completionTokens: number, totalTokens: number },
 *   sources: Array<{ source: string, index: number, text: string, score: number }>,
 *   dropped: number, finishReason?: string,
 * }} ChatResult
 */

export class Natlas {
  /**
   * @param {{ baseURL?: string, model?: string, apiKey?: string, timeoutMs?: number, retries?: number, fetch?: typeof fetch }} [options]
   */
  constructor(options = {}) {
    this.baseURL = (options.baseURL || env("NATLAS_BASE_URL") || "http://localhost:11434/v1")
      .replace(/\/+$/, "")
      .replace(/\/chat\/completions$/, "");
    this.model = options.model || env("NATLAS_MODEL") || "n-atlas";
    this.apiKey = options.apiKey ?? env("NATLAS_API_KEY") ?? "";
    // N-ATLAS on a CPU writes ~1–5 tokens a second, so allow long replies.
    this.timeoutMs = options.timeoutMs ?? 600_000;
    this.retries = options.retries ?? 2;
    this.fetch = options.fetch || globalThis.fetch.bind(globalThis);
  }

  /**
   * Ask N-ATLAS. `input` is a question, or a conversation ([{ role, content }]).
   * @param {string | Message[]} input
   * @param {ChatOptions} [options]
   * @returns {Promise<ChatResult>}
   */
  async chat(input, options = {}) {
    const { body, sources, dropped } = this.#request(input, options, false);
    const started = Date.now();
    const data = await this.#withRetries(options, async () => {
      const call = await this.#post(body, options);
      try {
        return await call.res.json();
      } catch (err) {
        throw toNatlasError(err, options, call.signal.reason, this);
      } finally {
        call.end();
      }
    });
    const choice = data?.choices?.[0];
    const text = choice?.message?.content ?? "";
    if (!text) throw new NatlasError("empty", "N-ATLAS returned an empty reply", { hint: "try again, or raise maxTokens" });
    return {
      text,
      model: data.model || this.model,
      latencyMs: Date.now() - started,
      usage: usage(data.usage),
      sources,
      dropped,
      finishReason: choice.finish_reason,
    };
  }

  /** Just the text of the reply. */
  async generate(prompt, options = {}) {
    return (await this.chat(prompt, options)).text;
  }

  /**
   * Stream the reply as it's written.
   *
   *   const s = natlas.stream("Tell me about Lagos");
   *   for await (const delta of s) process.stdout.write(delta);
   *   const { usage, sources } = await s.done;
   *
   * @param {string | Message[]} input
   * @param {ChatOptions} [options]
   * @returns {AsyncGenerator<string> & { done: Promise<ChatResult> }}
   */
  stream(input, options = {}) {
    let settle;
    const done = new Promise((resolve, reject) => (settle = { resolve, reject }));
    done.catch(() => {}); // only surfaces if awaited
    const gen = this.#streamGen(input, options, settle);
    return Object.assign(gen, { done });
  }

  /** Check the server is up and the model is loaded. Resolves { ok, latencyMs } or throws a NatlasError. */
  async ping() {
    const started = Date.now();
    await this.chat("ping", { maxTokens: 1, temperature: 0, retries: 0, timeoutMs: 120_000 });
    return { ok: true, latencyMs: Date.now() - started };
  }

  async *#streamGen(input, options, settle) {
    let text = "";
    let call;
    let reader;
    try {
      const { body, sources, dropped } = this.#request(input, options, true);
      const started = Date.now();
      call = await this.#withRetries(options, () => this.#post(body, options));
      if (!call.res.body) throw new NatlasError("http", "The server sent no stream", { hint: "check it supports stream: true" });
      reader = call.res.body.getReader();
      const decoder = new TextDecoder();
      let buffer = "";
      let tokens;
      let finishReason;
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split("\n");
        buffer = lines.pop() || "";
        for (const line of lines) {
          const trimmed = line.trim();
          if (!trimmed.startsWith("data:") || trimmed === "data: [DONE]") continue;
          let chunk;
          try {
            chunk = JSON.parse(trimmed.slice(5));
          } catch {
            continue;
          }
          if (chunk.usage) tokens = usage(chunk.usage);
          const choice = chunk.choices?.[0];
          if (choice?.finish_reason) finishReason = choice.finish_reason;
          const delta = choice?.delta?.content;
          if (delta) {
            text += delta;
            yield delta;
          }
        }
      }
      settle.resolve({ text, model: this.model, latencyMs: Date.now() - started, usage: tokens, sources, dropped, finishReason });
    } catch (err) {
      const e = toNatlasError(err, options, call?.signal.reason, this);
      settle.reject(e);
      throw e;
    } finally {
      call?.end();
      reader?.cancel().catch(() => {});
      // Stopped early (break out of for-await): resolve with what arrived.
      settle.resolve({ text, model: this.model, latencyMs: 0, usage: undefined, sources: [], dropped: 0, finishReason: "cancelled" });
    }
  }

  #request(input, options, stream) {
    const maxTokens = options.maxTokens ?? 512;
    const history = typeof input === "string" ? [{ role: "user", content: input }] : [...input];
    const lastUser = [...history].reverse().find((m) => m.role === "user")?.content ?? "";

    const systemBits = [];
    const given = history.filter((m) => m.role === "system").map((m) => m.content);
    if (options.system) systemBits.push(options.system);
    systemBits.push(...given);
    if (options.language) {
      if (!LANGUAGES[options.language]) {
        throw new NatlasError("invalid", "Unknown language " + JSON.stringify(options.language), {
          hint: "use one of " + Object.keys(LANGUAGES).join(", "),
        });
      }
      systemBits.push("Respond in " + LANGUAGES[options.language] + ".");
    }
    let system = systemBits.join(" ");
    let sources = [];
    if (options.knowledge) {
      sources = options.knowledge.search(lastUser, options.k ?? 3);
      if (sources.length) system = (system ? system + "\n\n" : "") + FACTS_HEADER + Knowledge.format(sources);
    }
    const turns = history.filter((m) => m.role !== "system");
    const { messages, dropped } = fitContext(system ? [{ role: "system", content: system }, ...turns] : turns, { maxTokens });

    const penalty = options.repetitionPenalty === undefined ? NATLAS.repetitionPenalty : options.repetitionPenalty;
    const body = {
      model: this.model,
      messages,
      temperature: options.temperature ?? NATLAS.temperature,
      max_tokens: maxTokens,
      stream,
      ...(stream ? { stream_options: { include_usage: true } } : {}),
      ...(options.stop ? { stop: options.stop } : {}),
      // vLLM/TGI read repetition_penalty, llama.cpp reads repeat_penalty; others ignore them.
      ...(penalty ? { repetition_penalty: penalty, repeat_penalty: penalty } : {}),
    };
    return { body, sources, dropped };
  }

  async #post(body, options) {
    const controller = new AbortController();
    const timeoutMs = options.timeoutMs ?? this.timeoutMs;
    const timer = setTimeout(() => controller.abort("timeout"), timeoutMs);
    const external = options.signal;
    if (external?.aborted) controller.abort("aborted");
    else external?.addEventListener("abort", () => controller.abort("aborted"), { once: true });
    let res;
    try {
      res = await this.fetch(this.baseURL + "/chat/completions", {
        method: "POST",
        headers: {
          "content-type": "application/json",
          ...(this.apiKey ? { authorization: "Bearer " + this.apiKey } : {}),
        },
        body: JSON.stringify(body),
        signal: controller.signal,
      });
    } catch (err) {
      clearTimeout(timer);
      throw toNatlasError(err, options, controller.signal.reason, this);
    }
    if (!res.ok) {
      const detail = await res.text().catch(() => "");
      clearTimeout(timer);
      throw httpError(res.status, detail, this);
    }
    // The timeout keeps running while the body is read; end() stops it.
    return { res, signal: controller.signal, end: () => clearTimeout(timer) };
  }

  async #withRetries(options, attempt) {
    const retries = options.retries ?? this.retries;
    for (let i = 0; ; i++) {
      try {
        return await attempt();
      } catch (err) {
        const e = toNatlasError(err, options);
        const retryable = e.code === "unreachable" || (e.code === "http" && (e.status === 429 || e.status >= 500));
        if (!retryable || i >= retries || options.signal?.aborted) throw e;
        await new Promise((r) => setTimeout(r, 500 * 2 ** i));
      }
    }
  }
}

function usage(u) {
  return u ? { promptTokens: u.prompt_tokens, completionTokens: u.completion_tokens, totalTokens: u.total_tokens } : undefined;
}

function httpError(status, detail, client) {
  const text = String(detail).slice(0, 300);
  if (status === 404 && /model/i.test(text)) {
    return new NatlasError("model_missing", "Model " + JSON.stringify(client.model) + " isn't on the server", {
      status,
      hint: "with Ollama, run `ollama list` to see its name, or create it: `ollama create n-atlas -f Modelfile`; or set NATLAS_MODEL",
    });
  }
  if (status === 401 || status === 403) {
    return new NatlasError("auth", "The server refused the API key (HTTP " + status + ")", { status, hint: "check NATLAS_API_KEY" });
  }
  if (status === 404) {
    return new NatlasError("http", "No chat endpoint at " + client.baseURL + "/chat/completions (HTTP 404)", {
      status,
      hint: "NATLAS_BASE_URL should end in /v1, e.g. http://localhost:11434/v1",
    });
  }
  return new NatlasError("http", "N-ATLAS server returned HTTP " + status + (text ? ": " + text : ""), { status });
}

function toNatlasError(err, options, reason, client) {
  if (err instanceof NatlasError) return err;
  if (reason === "timeout") {
    return new NatlasError("timeout", "N-ATLAS took longer than " + Math.round((options.timeoutMs ?? client?.timeoutMs ?? 0) / 1000) + "s", {
      hint: "on a CPU it writes ~1–5 tokens a second — lower maxTokens, raise timeoutMs, or use a GPU",
      cause: err,
    });
  }
  if (reason === "aborted" || options.signal?.aborted || err?.name === "AbortError") {
    return new NatlasError("aborted", "Request cancelled", { cause: err });
  }
  return new NatlasError("unreachable", "Can't reach N-ATLAS at " + (client?.baseURL ?? "the server"), {
    hint: "is it running? Start Ollama with `ollama serve`, or set NATLAS_BASE_URL",
    cause: err,
  });
}

/** Shortcut for one-off calls with the default client. */
export async function chat(input, options) {
  return new Natlas().chat(input, options);
}

/** Back-compatible helper used by Launchpad's exported projects. */
export async function generate(prompt, { system, temperature, maxTokens, language } = {}) {
  return (await new Natlas().chat(prompt, { system, temperature, maxTokens, language })).text;
}

