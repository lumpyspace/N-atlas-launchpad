STOPWORDS = set(
    "a an the and or but if of to in on at for from by with about as is are was were be been being do does did have has had i you he she it we they me my your our their this that these those what which who whom how when where why can could will would should may might must not no yes so than then there here just also into over under up down out more most some any all each other such only own same very s t don wetin abeg dey na wey una dem e".split()
)
_SUFFIXES = ["ation", "ion", "ing", "ed", "or", "er", "ly"]


def _stem(w):
    if len(w) > 4 and w.endswith("s") and not w.endswith("ss"):
        w = w[:-1]
    for suffix in _SUFFIXES:
        if w.endswith(suffix) and len(w) - len(suffix) >= 4:
            return w[: -len(suffix)]
    return w


def tokenize(text: str) -> List[str]:
    """Lowercase, strip accents ("kaaro" matches "káàárọ̀"), split into words, light stemming."""
    t = "".join(c for c in unicodedata.normalize("NFD", text) if unicodedata.category(c) != "Mn").lower()
    return [_stem(w) for w in re.split(r"[^\w]+|_", t) if len(w) > 1 and w not in STOPWORDS]


def chunk_text(text: str, target_words: int = 160, max_words: int = 240) -> List[str]:
    """Split text into passages of ~160 words, keeping paragraphs together."""
    paragraphs = [re.sub(r"[ \t]+", " ", p).strip() for p in re.split(r"\n\s*\n", text.replace("\r\n", "\n").replace("\r", "\n"))]
    chunks, current, count = [], [], 0
    for para in filter(None, paragraphs):
        words = len(para.split())
        if words > max_words:
            if current:
                chunks.append("\n\n".join(current))
            current, count = [], 0
            buf, n = [], 0
            for sentence in re.split(r"(?<=[.!?])\s+", para):
                w = len(sentence.split())
                if n + w > target_words and buf:
                    chunks.append(" ".join(buf))
                    buf, n = [], 0
                buf.append(sentence)
                n += w
            if buf:
                chunks.append(" ".join(buf))
            continue
        if count + words > target_words and current:
            chunks.append("\n\n".join(current))
            current, count = [], 0
        current.append(para)
        count += words
    if current:
        chunks.append("\n\n".join(current))
    return chunks


@dataclass
class Source:
    source: str
    index: int
    text: str
    score: float


class Knowledge:
    """The documents your app answers from. Keyword search (BM25) — no embedding
    model needed, works offline, and matches across English and Nigerian languages.

        kb = Knowledge()
        kb.add("prices.txt", open("prices.txt", encoding="utf-8").read())
        natlas.chat("How much is rice?", knowledge=kb)
    """

    def __init__(self, passages=None):
        self.passages = []
        self._stats = None
        for p in passages or []:
            self._push(p["source"], p["index"], p["text"])

    @classmethod
    def from_json(cls, data):
        """Launchpad's knowledge/passages.json (a path, JSON text or list), or a project's documents."""
        if isinstance(data, str):
            data = json.loads(data) if data.lstrip().startswith("[") else json.load(open(data, encoding="utf-8"))
        kb = cls()
        for item in data:
            if isinstance(item.get("chunks"), list):
                for i, c in enumerate(item["chunks"]):
                    kb._push(item["name"], i + 1, c["text"])
            else:
                kb._push(item["source"], item["index"], item["text"])
        return kb

    def add(self, source: str, text: str) -> int:
        """Add a document; it's split into passages. Returns the number of passages."""
        chunks = chunk_text(text)
        for i, t in enumerate(chunks):
            self._push(source, i + 1, t)
        return len(chunks)

    def __len__(self):
        return len(self.passages)

    def _push(self, source, index, text):
        self.passages.append({"source": source, "index": index, "text": text, "terms": tokenize(text)})
        self._stats = None

    def _index(self):
        if self._stats is None:
            df = {}
            for p in self.passages:
                for t in set(p["terms"]):
                    df[t] = df.get(t, 0) + 1
            avg = (sum(len(p["terms"]) for p in self.passages) / len(self.passages)) if self.passages else 1
            self._stats = (df, avg or 1)
        return self._stats

    def search(self, query: str, k: int = 3) -> List[Source]:
        """The k most relevant passages."""
        q = set(tokenize(query))
        if not q or not self.passages:
            return []
        df, avg = self._index()
        n_docs = len(self.passages)
        hits = []
        for p in self.passages:
            tf = {}
            for t in p["terms"]:
                tf[t] = tf.get(t, 0) + 1
            score = 0.0
            for term in q:
                f = tf.get(term)
                if not f:
                    continue
                n = df.get(term, 0)
                idf = math.log(1 + (n_docs - n + 0.5) / (n + 0.5))
                score += idf * ((f * 2.4) / (f + 1.4 * (0.25 + 0.75 * len(p["terms"]) / avg)))
            if score > 0:
                hits.append(Source(p["source"], p["index"], p["text"], score))
        hits.sort(key=lambda h: -h.score)
        return hits[:k]

    @staticmethod
    def format(hits: List[Source]) -> str:
        """Passages as a facts block, each labelled with its source."""
        return "\n\n".join("[%s — passage %d]\n%s" % (h.source, h.index, h.text) for h in hits)


# --- Language -----------------------------------------------------------------

_W = r"(?<![^\W\d_])(%s)(?![^\W\d_])"
_LANG_MARKERS = {
    "yo": (re.compile(r"[ẹọṣ]|[àáèéìíòóùú]"), re.compile(_W % "mo|emi|ti|naa|fun|si|lo|wa|sọ|wọn|àwọn|ilé|ọjọ́|kò|àti|tó|yìí", re.I)),
    "ha": (re.compile(r"[ɓɗƙ]"), re.compile(_W % "ya|ba|ne|ce|da|shi|ta|mu|su|mai|amma|don|kuma|daga|wani|kamar", re.I)),
    "ig": (re.compile(r"[ịụ]"), re.compile(_W % "nke|chi|gị|ha|ndi|otu|bụ|dị|ebe|ihe", re.I)),
    "pid": (None, re.compile(_W % "wetin|abeg|dey|oga|wahala|sabi|una|comot|waka|chop|naim|no be|how far|na im|dem", re.I)),
}


def detect_language(text: str) -> str:
    """Best guess at the language of a reply: "en", "yo", "ha", "ig" or "pid".
    A heuristic for checking N-ATLAS answered in the language you asked for —
    unreliable under ~10 words."""
    best, best_score = "en", 1
    for code, (chars, words) in _LANG_MARKERS.items():
        score = len(words.findall(text)) * (2 if code == "pid" else 1)
        if chars is not None and chars.search(text):
            score += 3
        if score > best_score:
            best, best_score = code, score
    return best


# --- Client -------------------------------------------------------------------


@dataclass
class Usage:
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int


@dataclass
class ChatResult:
    text: str
    model: str
    latency_ms: int
    usage: Optional[Usage] = None
    sources: List[Source] = field(default_factory=list)
    dropped: int = 0
    finish_reason: Optional[str] = None


def _usage(u):
    return Usage(u.get("prompt_tokens", 0), u.get("completion_tokens", 0), u.get("total_tokens", 0)) if u else None


class Stream:
    """Iterate to get the reply as it's written; `.result` is set when it ends.

        s = natlas.stream("Tell me about Lagos")
        for delta in s:
            print(delta, end="", flush=True)
        print(s.result.usage)
    """

    def __init__(self, gen):
        self._gen = gen
        self.result: Optional[ChatResult] = None

    def __iter__(self):
        self.result = yield from self._gen
        return self.result

    @property
    def text(self) -> str:
        return self.result.text if self.result else ""


class Natlas:
    def __init__(self, base_url=None, model=None, api_key=None, timeout=600, retries=2):
        """base_url defaults to NATLAS_BASE_URL, else Ollama at http://localhost:11434/v1.
        `timeout` is in seconds: N-ATLAS on a CPU writes ~1–5 tokens a second."""
        base = base_url or os.environ.get("NATLAS_BASE_URL") or "http://localhost:11434/v1"
        self.base_url = re.sub(r"/chat/completions$", "", base.rstrip("/"))
        self.model = model or os.environ.get("NATLAS_MODEL") or "n-atlas"
        self.api_key = api_key if api_key is not None else os.environ.get("NATLAS_API_KEY", "")
        self.timeout = timeout
        self.retries = retries

    def chat(self, input: Union[str, List[Message]], **options) -> ChatResult:
        """Ask N-ATLAS. `input` is a question, or a conversation ([{"role", "content"}]).

        Options: system, language ("en"|"yo"|"ha"|"ig"|"pid"), knowledge, k=3,
        temperature=0.1, max_tokens=512, repetition_penalty=1.12 (None to leave
        it to the server), stop, timeout, retries.
        """
        body, sources, dropped = self._request(input, options, stream=False)
        started = time.time()

        def call():
            with self._post(body, options) as res:
                return json.loads(res.read().decode("utf-8"))

        data = self._with_retries(options, call)
        choice = (data.get("choices") or [{}])[0]
        text = (choice.get("message") or {}).get("content") or ""
        if not text:
            raise NatlasError("empty", "N-ATLAS returned an empty reply", hint="try again, or raise max_tokens")
        return ChatResult(
            text=text,
            model=data.get("model") or self.model,
            latency_ms=int((time.time() - started) * 1000),
            usage=_usage(data.get("usage")),
            sources=sources,
            dropped=dropped,
            finish_reason=choice.get("finish_reason"),
        )

    def generate(self, prompt: str, **options) -> str:
        """Just the text of the reply."""
        return self.chat(prompt, **options).text

    def stream(self, input: Union[str, List[Message]], **options) -> Stream:
        """Stream the reply; same options as chat()."""
        return Stream(self._stream(input, options))

    def ping(self) -> int:
        """Check the server is up and the model loads. Returns latency in ms, or raises NatlasError."""
        started = time.time()
        self.chat("ping", max_tokens=1, temperature=0, retries=0, timeout=120)
        return int((time.time() - started) * 1000)

    def _stream(self, input, options) -> Iterator[str]:
        body, sources, dropped = self._request(input, options, stream=True)
        started = time.time()
        res = self._with_retries(options, lambda: self._post(body, options))
        text, usage, finish = "", None, None
        try:
            for raw in res:
                line = raw.decode("utf-8").strip()
                if not line.startswith("data:") or line == "data: [DONE]":
                    continue
                try:
                    chunk = json.loads(line[5:])
                except ValueError:
                    continue
                if chunk.get("usage"):
                    usage = _usage(chunk["usage"])
                choices = chunk.get("choices") or []
                if choices:
                    finish = choices[0].get("finish_reason") or finish
                    delta = (choices[0].get("delta") or {}).get("content")
                    if delta:
                        text += delta
                        yield delta
        except socket.timeout:
            raise self._timeout_error(options)
        finally:
            res.close()
        return ChatResult(text, self.model, int((time.time() - started) * 1000), usage, sources, dropped, finish)

    def _request(self, input, options, stream):
        unknown = set(options) - {"system", "language", "knowledge", "k", "temperature", "max_tokens", "repetition_penalty", "stop", "timeout", "retries"}
        if unknown:
            raise NatlasError("invalid", "Unknown option(s): " + ", ".join(sorted(unknown)))
        max_tokens = options.get("max_tokens", 512)
        history = [{"role": "user", "content": input}] if isinstance(input, str) else list(input)
        last_user = next((m["content"] for m in reversed(history) if m["role"] == "user"), "")

        bits = [options["system"]] if options.get("system") else []
        bits += [m["content"] for m in history if m["role"] == "system"]
        language = options.get("language")
        if language:
            if language not in LANGUAGES:
                raise NatlasError("invalid", "Unknown language %r" % language, hint="use one of " + ", ".join(LANGUAGES))
            bits.append("Respond in %s." % LANGUAGES[language])
        system = " ".join(bits)
        sources = []
        if options.get("knowledge") is not None:
            sources = options["knowledge"].search(last_user, options.get("k", 3))
            if sources:
                system = (system + "\n\n" if system else "") + FACTS_HEADER + Knowledge.format(sources)
        turns = [m for m in history if m["role"] != "system"]
        messages, dropped = fit_context(([{"role": "system", "content": system}] if system else []) + turns, max_tokens)

        penalty = options.get("repetition_penalty", NATLAS["repetition_penalty"])
        body = {
            "model": self.model,
            "messages": messages,
            "temperature": options.get("temperature", NATLAS["temperature"]),
            "max_tokens": max_tokens,
            "stream": stream,
        }
        if stream:
            body["stream_options"] = {"include_usage": True}
        if options.get("stop"):
            body["stop"] = options["stop"]
        if penalty:
            # vLLM/TGI read repetition_penalty, llama.cpp reads repeat_penalty; others ignore them.
            body["repetition_penalty"] = body["repeat_penalty"] = penalty
        return body, sources, dropped

    def _post(self, body, options):
        headers = {"content-type": "application/json"}
        if self.api_key:
            headers["authorization"] = "Bearer " + self.api_key
        req = urllib.request.Request(
            self.base_url + "/chat/completions", data=json.dumps(body).encode("utf-8"), headers=headers, method="POST"
        )
        try:
            return urllib.request.urlopen(req, timeout=options.get("timeout", self.timeout))
        except urllib.error.HTTPError as e:
            raise self._http_error(e.code, e.read().decode("utf-8", "replace"))
        except socket.timeout:
            raise self._timeout_error(options)
        except urllib.error.URLError as e:
            if isinstance(e.reason, socket.timeout):
                raise self._timeout_error(options)
            raise NatlasError(
                "unreachable",
                "Can't reach N-ATLAS at " + self.base_url,
                hint="is it running? Start Ollama with `ollama serve`, or set NATLAS_BASE_URL",
            )

    def _with_retries(self, options, attempt):
        retries = options.get("retries", self.retries)
        i = 0
        while True:
            try:
                return attempt()
            except socket.timeout:
                raise self._timeout_error(options)
            except NatlasError as e:
                retryable = e.code == "unreachable" or (e.code == "http" and (e.status == 429 or (e.status or 0) >= 500))
                if not retryable or i >= retries:
                    raise
                time.sleep(0.5 * 2**i)
                i += 1

    def _timeout_error(self, options):
        return NatlasError(
            "timeout",
            "N-ATLAS didn't answer within %ss" % options.get("timeout", self.timeout),
            hint="on a CPU it writes ~1–5 tokens a second — lower max_tokens, raise timeout, or use a GPU",
        )

    def _http_error(self, status, detail):
        detail = detail[:300]
        if status == 404 and re.search("model", detail, re.I):
            return NatlasError(
                "model_missing",
                "Model %r isn't on the server" % self.model,
                status,
                "with Ollama, run `ollama list` to see its name, or create it: `ollama create n-atlas -f Modelfile`; or set NATLAS_MODEL",
            )
        if status in (401, 403):
            return NatlasError("auth", "The server refused the API key (HTTP %d)" % status, status, "check NATLAS_API_KEY")
        if status == 404:
            return NatlasError(
                "http",
                "No chat endpoint at %s/chat/completions (HTTP 404)" % self.base_url,
                status,
                "NATLAS_BASE_URL should end in /v1, e.g. http://localhost:11434/v1",
            )
        return NatlasError("http", "N-ATLAS server returned HTTP %d%s" % (status, ": " + detail if detail else ""), status)


def chat(input, **options) -> ChatResult:
    """Shortcut for one-off calls with the default client."""
    return Natlas().chat(input, **options)


def generate(prompt, system=None, temperature=None, max_tokens=512, language=None):
    """Back-compatible helper used by Launchpad's exported projects."""
    options = {"max_tokens": max_tokens}
    if system:
        options["system"] = system
    if temperature is not None:
        options["temperature"] = temperature
    if language:
        options["language"] = language
    return Natlas().chat(prompt, **options).text
