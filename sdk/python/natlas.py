def load_env(path: str = ".env") -> None:
    """Load KEY=VALUE lines from a .env file into the environment (existing variables win).

    Call it before creating Natlas(); a missing file is fine.
    """
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except OSError:
        return
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key and key not in os.environ:
            os.environ[key] = value


# --- Errors -------------------------------------------------------------------


class NatlasError(Exception):
    """Every failure has a `code` you can check and a `hint` that says what to do.

    code: "unreachable" | "model_missing" | "auth" | "http" | "timeout" | "empty" | "too_long" | "invalid"
    """

    def __init__(self, code, message, status=None, hint=None):
        super().__init__(message + (" — " + hint if hint else ""))
        self.code = code
        self.status = status
        self.hint = hint


# --- Tokens and context -------------------------------------------------------


def estimate_tokens(text: str) -> int:
    """Rough token count: ~4 characters per token for ASCII, fewer for accented text."""
    if not text:
        return 0
    ascii_chars = sum(1 for c in text if ord(c) < 128)
    return math.ceil(ascii_chars / 4 + (len(text) - ascii_chars) / 1.5)


def fit_context(messages: List[Message], max_tokens: int = 512, context_tokens: int = NATLAS["context_tokens"]):
    """Drop the oldest turns (never the system message or the latest message) until
    the conversation plus the reply fits. Returns (messages, dropped)."""

    def cost(m):
        return estimate_tokens(m["content"]) + 4

    system = [m for m in messages if m["role"] == "system"]
    rest = [m for m in messages if m["role"] != "system"]
    budget = context_tokens - max_tokens
    total = sum(cost(m) for m in system + rest)
    dropped = 0
    while total > budget and len(rest) > 1:
        total -= cost(rest.pop(0))
        dropped += 1
    if total > budget:
        raise NatlasError(
            "too_long",
            "The prompt is about %d tokens; N-ATLAS fits %d plus the reply" % (total, budget),
            hint="shorten the system prompt or the facts, or lower max_tokens",
        )
    return system + rest, dropped


