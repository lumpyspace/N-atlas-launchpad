import type { Blueprint } from "../api";
import { SDK_VERSION } from "./sdkSource";

export type ExportLang = "js" | "python";

/** The exported project's README: what it is, how to run it, and how it stays safe. */
export function readme(name: string, bp: Blueprint, lang: ExportLang, myTests: number): string {
  const js = lang === "js";
  const channel = bp.buildPlan?.channel?.id ?? "web";
  const game = channel === "game";
  const runner = js ? "npm test" : "python tests/run_tests.py";
  const start = js
    ? ["npm install", "npm start"]
    : ["python server.py"];
  const extra = js
    ? [
        'npm run chat -- "What can you help me with?"   # one question from the terminal',
        "npm test                 # your test cases, scored (exits 1 on a failure)",
        "npm run test:eval        # quality prompts, for you to review",
        "npm run test:security    # the attacks, for you to review",
      ]
    : [
        'python chat.py "What can you help me with?"   # one question from the terminal',
        "python tests/run_tests.py     # your test cases, scored (exits 1 on a failure)",
        "python tests/run_eval.py      # quality prompts, for you to review",
        "python tests/run_security.py  # the attacks, for you to review",
      ];
  const files = js
    ? [
        "- `src/server.js` — your app's server: the chat page, `POST /api/chat`, and the safety checks below" +
          (channel === "whatsapp" ? ", plus the WhatsApp webhook" : channel === "telegram" ? ", plus the Telegram webhook" : ""),
        "- `public/index.html` — the chat page your users open (edit it freely)",
        "- `src/systemPrompt.js` — the instructions N-ATLAS follows, and `LANGUAGE`, the language your app replies in",
        "- `src/natlas.js` — the N-ATLAS SDK: every call to the model goes through it",
      ]
    : [
        "- `server.py` — your app's server: the chat page, `POST /api/chat`, and the safety checks below (standard library only)",
        "- `public/index.html` — the chat page your users open (edit it freely)",
        "- `system_prompt.py` — the instructions N-ATLAS follows, and `LANGUAGE`, the language your app replies in",
        "- `natlas.py` — the N-ATLAS SDK: every call to the model goes through it",
      ];

  return `# ${name}

An **N-ATLAS** app, generated by [N-ATLAS Launchpad](https://github.com/lumpyspace/N-atlas-launchpad).

## Run it

1. Make sure N-ATLAS is running — for example in Ollama (\`ollama serve\`). Launchpad's **Setup doctor** checks your setup.
2. Copy \`.env.example\` to \`.env\` and set where N-ATLAS is (\`NATLAS_BASE_URL\`) and the model's name (\`NATLAS_MODEL\`). The app reads \`.env\` when it starts${js ? " (Node 20.12 or newer)" : ""}.
3. Start the app:

\`\`\`bash
${start.join("\n")}
\`\`\`

${game ? "Your game calls the server's endpoints (see the comments in `src/server.js`)." : "Then open **http://localhost:3000** — that's your app. (Set `PORT` in `.env` to use another port.)"}

Other commands:

\`\`\`bash
${extra.join("\n")}
\`\`\`
${
  channel === "whatsapp"
    ? "\n**WhatsApp:** set `WA_TOKEN`, `WA_PHONE_NUMBER_ID` and `WA_VERIFY_TOKEN` in `.env` from your Meta app and point its webhook at `https://your-domain/webhook`. The chat page is there for testing.\n"
    : channel === "telegram"
      ? "\n**Telegram:** create a bot with @BotFather, set `TELEGRAM_TOKEN` in `.env`, and register `https://your-domain/telegram` as its webhook. The chat page is there for testing.\n"
      : ""
}
## What's inside

${files.join("\n")}

**N-ATLAS** is an open, Nigeria-focused language model (Nigerian English, Yoruba, Hausa, Igbo) with no public API:
you serve it yourself over an OpenAI-compatible endpoint — Ollama on a laptop, a GPU server, or a hosted endpoint.
The SDK (natlas ${SDK_VERSION}) sends N-ATLAS's recommended settings (temperature 0.1, repetition penalty 1.12),
the language instruction, retries busy servers and explains failures. Docs: https://github.com/lumpyspace/N-atlas-launchpad/tree/master/sdk

## Safety

Security is built in, in two layers:

1. **The system prompt is hardened** — it tells N-ATLAS to treat user messages as data, never reveal its instructions,
   ignore claims like "I am the developer", and keep its safety rules under role-play. Launchpad attacked it before export.
2. **The server checks in code**, which holds even when the model slips:
   - messages over 1,000 characters are refused, and each user is limited to 20 messages a minute;
   - a reply that contains the secret reference code planted in the system prompt, or a long line of the prompt,
     is replaced with a safe answer — so the prompt can't leak;
   - if N-ATLAS answers in the wrong language, the server asks once more, firmly.

Still yours to do before real users: serve it over HTTPS, keep \`.env\` out of git, never put passwords, keys or
other people's data in the system prompt, and re-run \`${runner}\` after every prompt change.

## Tests

- \`tests/my-tests.json\` — your ${myTests} test case${myTests === 1 ? "" : "s"} from Launchpad, each with checks (reply language,
  repetition, must / must-not mention, refusal, length, response time). \`${runner}\` scores every reply and fails on a
  problem; add a word to run only matching tests (\`${runner} price\`). Re-import the file in Launchpad to edit tests visually.
- \`.github/workflows/natlas-tests.yml\` — runs those tests on every push once you add a \`NATLAS_BASE_URL\` repository secret.
- \`finetune/\` — your 👍 replies as chat-format JSONL for fine-tuning, plus the 👎 ones to fix.
- \`tests/eval-tests.json\` and \`tests/security-tests.json\` — the quality prompts and attacks Launchpad ran, to replay and review.
`;
}
