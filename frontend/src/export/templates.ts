function jsFiles(
  name: string,
  bp: Blueprint,
  sp: string,
  evals: string,
  secs: string,
  myTests: number,
): Record<string, string> {
  return {
    "package.json": `{
  "name": "${slug(name)}",
  "version": "0.1.0",
  "description": "${name} — an N-ATLAS application generated by N-ATLAS Launchpad.",
  "type": "module",
  "engines": { "node": ">=18" },
  "scripts": {
    "chat": "node src/chat.js",
    "test": "node tests/run-tests.js",
    "test:eval": "node tests/run-eval.js",
    "test:security": "node tests/run-security.js"
  }
}
`,
    ".env.example": `# N-ATLAS is open-weights with no public API — point this at wherever you serve it.
# Local Ollama:   NATLAS_BASE_URL=http://localhost:11434/v1  NATLAS_MODEL=n-atlas
# Hosted GPU/HF:  NATLAS_BASE_URL=https://your-endpoint/v1   NATLAS_API_KEY=...
NATLAS_BASE_URL=http://localhost:11434/v1
NATLAS_API_KEY=
NATLAS_MODEL=n-atlas
`,
    "src/systemPrompt.js": `// Your application's system prompt (generated and hardened in Launchpad).
export const SYSTEM_PROMPT = ${sp};
`,
    "src/natlas.js": `// Minimal N-ATLAS client. Works with any OpenAI-compatible endpoint.
const BASE = (process.env.NATLAS_BASE_URL || "http://localhost:11434/v1").replace(/\\/$/, "");
const API_KEY = process.env.NATLAS_API_KEY || "";
const MODEL = process.env.NATLAS_MODEL || "n-atlas";

export async function generate(prompt, { system, temperature = 0.2, maxTokens = 512 } = {}) {
  const messages = [];
  if (system) messages.push({ role: "system", content: system });
  messages.push({ role: "user", content: prompt });

  const res = await fetch(BASE + "/chat/completions", {
    method: "POST",
    headers: {
      "content-type": "application/json",
      ...(API_KEY ? { authorization: "Bearer " + API_KEY } : {}),
    },
    body: JSON.stringify({ model: MODEL, messages, temperature, max_tokens: maxTokens, stream: false }),
  });
  if (!res.ok) throw new Error("N-ATLAS request failed: HTTP " + res.status);
  const data = await res.json();
  return data.choices?.[0]?.message?.content ?? "";
}
`,
    "src/chat.js": `import { generate } from "./natlas.js";
import { SYSTEM_PROMPT } from "./systemPrompt.js";

const prompt = process.argv.slice(2).join(" ") || "Hello! What can you help me with?";
const answer = await generate(prompt, { system: SYSTEM_PROMPT });
console.log(answer);
`,
    "tests/eval-tests.json": evals + "\n",
    "tests/security-tests.json": secs + "\n",
    "tests/run-eval.js": `// Replays the evaluation prompts against your configured N-ATLAS endpoint.
import { readFile } from "node:fs/promises";
import { generate } from "../src/natlas.js";
import { SYSTEM_PROMPT } from "../src/systemPrompt.js";

const tests = JSON.parse(await readFile(new URL("./eval-tests.json", import.meta.url), "utf8"));
for (const t of tests) {
  const answer = await generate(t.prompt, { system: SYSTEM_PROMPT });
  console.log("\\n[" + t.id + "] (" + t.category + ")\\nQ: " + t.prompt + "\\nA: " + answer);
}
`,
    "tests/run-security.js": `// Replays the security attacks against your app. Inspect each response:
// it should refuse/ignore the attack and never reveal its system prompt.
import { readFile } from "node:fs/promises";
import { generate } from "../src/natlas.js";
import { SYSTEM_PROMPT } from "../src/systemPrompt.js";

const tests = JSON.parse(await readFile(new URL("./security-tests.json", import.meta.url), "utf8"));
for (const t of tests) {
  const answer = await generate(t.prompt, { system: SYSTEM_PROMPT });
  console.log("\\n[" + t.severity + "] " + t.id + " (" + t.category + ")");
  console.log("Attack:   " + t.prompt);
  console.log("Expected: " + t.expectedBehavior);
  console.log("Response: " + answer);
}
`,
    "README.md": readme(name, bp, "js", myTests),
  };
}

// --- Python -----------------------------------------------------------------

function pyFiles(
  name: string,
  bp: Blueprint,
  sp: string,
  evals: string,
  secs: string,
  myTests: number,
): Record<string, string> {
  return {
    "requirements.txt": "requests>=2.31\n",
    ".env.example": `NATLAS_BASE_URL=http://localhost:11434/v1
NATLAS_API_KEY=
NATLAS_MODEL=n-atlas
`,
    "system_prompt.py": `# Your application's system prompt (generated and hardened in Launchpad).
SYSTEM_PROMPT = ${sp}
`,
    "natlas.py": `"""Minimal N-ATLAS client for any OpenAI-compatible endpoint."""
import os
import requests

BASE = os.environ.get("NATLAS_BASE_URL", "http://localhost:11434/v1").rstrip("/")
API_KEY = os.environ.get("NATLAS_API_KEY", "")
MODEL = os.environ.get("NATLAS_MODEL", "n-atlas")


def generate(prompt, system=None, temperature=0.2, max_tokens=512):
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})
    headers = {"content-type": "application/json"}
    if API_KEY:
        headers["authorization"] = "Bearer " + API_KEY
    resp = requests.post(
        BASE + "/chat/completions",
        headers=headers,
        json={"model": MODEL, "messages": messages, "temperature": temperature,
              "max_tokens": max_tokens, "stream": False},
        timeout=300,
    )
    resp.raise_for_status()
    data = resp.json()
    return data["choices"][0]["message"]["content"]
`,
    "chat.py": `import sys
from natlas import generate
from system_prompt import SYSTEM_PROMPT

prompt = " ".join(sys.argv[1:]) or "Hello! What can you help me with?"
print(generate(prompt, system=SYSTEM_PROMPT))
`,
    "tests/eval-tests.json": evals + "\n",
    "tests/security-tests.json": secs + "\n",
    "tests/run_eval.py": `import json, os
from natlas import generate
from system_prompt import SYSTEM_PROMPT

here = os.path.dirname(__file__)
tests = json.load(open(os.path.join(here, "eval-tests.json"), encoding="utf-8"))
for t in tests:
    answer = generate(t["prompt"], system=SYSTEM_PROMPT)
    print(f"\\n[{t['id']}] ({t['category']})\\nQ: {t['prompt']}\\nA: {answer}")
`,
    "tests/run_security.py": `import json, os
from natlas import generate
from system_prompt import SYSTEM_PROMPT

here = os.path.dirname(__file__)
tests = json.load(open(os.path.join(here, "security-tests.json"), encoding="utf-8"))
for t in tests:
    answer = generate(t["prompt"], system=SYSTEM_PROMPT)
    print(f"\\n[{t['severity']}] {t['id']} ({t['category']})")
    print("Attack:   " + t["prompt"])
    print("Expected: " + t["expectedBehavior"])
    print("Response: " + answer)
`,
    "README.md": readme(name, bp, "python", myTests),
  };
}

// --- README (shared) --------------------------------------------------------

function readme(name: string, bp: Blueprint, lang: ExportLang, myTests: number): string {
  const run =
    lang === "js"
      ? ["npm install  # (no deps; Node 18+ required)", "node src/chat.js \"What can you help me with?\"", "npm test               # your test cases, scored (exit 1 on failure)", "npm run test:eval", "npm run test:security"]
      : ["python -m venv .venv && . .venv/bin/activate", "pip install -r requirements.txt", "python chat.py \"What can you help me with?\"", "python tests/run_tests.py   # your test cases, scored (exit 1 on failure)", "python tests/run_eval.py", "python tests/run_security.py"];
  const runner = lang === "js" ? "node tests/run-tests.js" : "python tests/run_tests.py";

  return `# ${name}

An **N-ATLAS** application, generated by [N-ATLAS Launchpad](https://github.com/).
Sector: **${bp.sector}**.

## What is N-ATLAS?

N-ATLAS is an open, Nigeria-focused large language model (Nigerian English,
Yoruba, Hausa, Igbo). It has no public API — you run it yourself and serve it
over an OpenAI-compatible HTTP endpoint (local Ollama, a GPU server, or a
Hugging Face Inference Endpoint).

## Setup

1. Serve N-ATLAS and note its endpoint (e.g. Ollama at \`http://localhost:11434/v1\`).
2. Copy \`.env.example\` to \`.env\` and set \`NATLAS_BASE_URL\`, \`NATLAS_MODEL\`, and \`NATLAS_API_KEY\` if needed.
3. Run:

\`\`\`bash
${run.join("\n")}
\`\`\`

## How the N-ATLAS integration works

All model calls go through a single small client (${lang === "js" ? "`src/natlas.js`" : "`natlas.py`"})
that posts to \`/chat/completions\` in the OpenAI format. Swap the endpoint via
env vars without touching the rest of the code.

## System prompt

Your app's behaviour is defined by the system prompt in
${lang === "js" ? "`src/systemPrompt.js`" : "`system_prompt.py`"} — generated from your
idea and hardened against prompt-injection / system-prompt-extraction attacks in
Launchpad.

## Tests

- \`tests/my-tests.json\` — your ${myTests} test case${myTests === 1 ? "" : "s"} from Launchpad, each with
  checks (reply language, no repetition loops, must/must-not mention, refusal,
  latency). \`${runner}\` scores every reply and exits non-zero on a failure;
  pass a word to run a subset (\`${runner} armyworm\`). Re-import the file in
  Launchpad's Evaluate step to edit tests visually.
- \`.github/workflows/natlas-tests.yml\` — runs those tests on every push once you
  add a \`NATLAS_BASE_URL\` repository secret.
- \`finetune/\` — your 👍 replies as chat-format JSONL for fine-tuning, plus the 👎
  ones to fix (see \`finetune/README.md\`).
- \`tests/eval-tests.json\` — quality & Nigerian-context prompts. The runner replays
  them so you can review answers (extend with your own scoring).
- \`tests/security-tests.json\` — controlled attacks (prompt injection, extraction,
  jailbreak, …) with the expected safe behaviour and mitigations.

> Note: some sophisticated attacks (e.g. smuggled injection) need
> application-layer input handling in addition to a hardened system prompt.

## Methodology

Evaluation uses declarative checks (keyword/refusal/format) — fast and
transparent. Security detection is deterministic (did the model leak a planted
reference code? did it obey an injected instruction? did it refuse?). Both are
designed so you can later plug in an LLM judge for deeper scoring.
`;
}
