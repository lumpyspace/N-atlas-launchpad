function pyFiles(
  name: string,
  bp: Blueprint,
  sp: string,
  evals: string,
  secs: string,
  myTests: number,
): Record<string, string> {
  return {
    "requirements.txt": "# No dependencies: natlas.py uses only the Python standard library.\n",
    ".env.example": `NATLAS_BASE_URL=http://localhost:11434/v1
NATLAS_API_KEY=
NATLAS_MODEL=n-atlas
`,
    "system_prompt.py": `# Your application's system prompt (generated and hardened in Launchpad).
SYSTEM_PROMPT = ${sp}
`,
    // The N-ATLAS SDK (sdk/python in the Launchpad repo), standard library only.
    "natlas.py": SDK_PY,
    "chat.py": `import sys
from natlas import Natlas
from system_prompt import SYSTEM_PROMPT

prompt = " ".join(sys.argv[1:]) or "Hello! What can you help me with?"
# Streams the reply as N-ATLAS writes it. Add language="yo" | "ha" | "ig" | "pid" to pick a language.
for delta in Natlas().stream(prompt, system=SYSTEM_PROMPT):
    print(delta, end="", flush=True)
print()
`,
    "tests/eval-tests.json": evals + "\n",
    "tests/security-tests.json": secs + "\n",
    "tests/run_eval.py": `import json, os
from natlas import generate
from system_prompt import SYSTEM_PROMPT

here = os.path.dirname(__file__)
tests = json.load(open(os.path.join(here, "eval-tests.json"), encoding="utf-8"))
for t in tests:
    answer = generate(t["prompt"], system=SYSTEM_PROMPT)
    print(f"\\n[{t['id']}] ({t['category']})\\nQ: {t['prompt']}\\nA: {answer}")
`,
    "tests/run_security.py": `import json, os
from natlas import generate
from system_prompt import SYSTEM_PROMPT

here = os.path.dirname(__file__)
tests = json.load(open(os.path.join(here, "security-tests.json"), encoding="utf-8"))
for t in tests:
    answer = generate(t["prompt"], system=SYSTEM_PROMPT)
    print(f"\\n[{t['severity']}] {t['id']} ({t['category']})")
    print("Attack:   " + t["prompt"])
    print("Expected: " + t["expectedBehavior"])
    print("Response: " + answer)
`,
    "README.md": readme(name, bp, "python", myTests),
  };
}

// --- README (shared) --------------------------------------------------------

function readme(name: string, bp: Blueprint, lang: ExportLang, myTests: number): string {
  const run =
    lang === "js"
      ? ["npm install  # Node 18+ required", "npm start             # your app's server (src/server.js)", "node src/chat.js \"What can you help me with?\"", "npm test               # your test cases, scored (exit 1 on failure)", "npm run test:eval", "npm run test:security"]
      : ["python -m venv .venv && . .venv/bin/activate", "pip install -r requirements.txt", "python chat.py \"What can you help me with?\"", "python tests/run_tests.py   # your test cases, scored (exit 1 on failure)", "python tests/run_eval.py", "python tests/run_security.py"];
  const runner = lang === "js" ? "node tests/run-tests.js" : "python tests/run_tests.py";

  return `# ${name}

An **N-ATLAS** application, generated by [N-ATLAS Launchpad](https://github.com/lumpyspace/N-atlas-launchpad).
Sector: **${bp.sector}**.

## What is N-ATLAS?

N-ATLAS is an open, Nigeria-focused large language model (Nigerian English,
Yoruba, Hausa, Igbo). It has no public API — you run it yourself and serve it
over an OpenAI-compatible HTTP endpoint (local Ollama, a GPU server, or a
Hugging Face Inference Endpoint).

## Setup

1. Serve N-ATLAS and note its endpoint (e.g. Ollama at \`http://localhost:11434/v1\`).
2. Copy \`.env.example\` to \`.env\` and set \`NATLAS_BASE_URL\`, \`NATLAS_MODEL\`, and \`NATLAS_API_KEY\` if needed.
3. Run:

\`\`\`bash
${run.join("\n")}
\`\`\`

## How the N-ATLAS integration works

All model calls go through the N-ATLAS SDK (${lang === "js" ? "`src/natlas.js`" : "`natlas.py`"},
natlas ${SDK_VERSION}) — one file, no dependencies. It posts to \`/chat/completions\` in
the OpenAI format with N-ATLAS's recommended settings (temperature 0.1, repetition
penalty 1.12), adds "Respond in …" language hints, keeps conversations inside the
8,092-token context, streams, retries busy servers, and turns failures into errors
with a \`code\` and a \`hint\` (e.g. "is Ollama running?"). Swap the endpoint via
env vars without touching the rest of the code. Docs:
https://github.com/lumpyspace/N-atlas-launchpad/tree/master/sdk

## System prompt

Your app's behaviour is defined by the system prompt in
${lang === "js" ? "`src/systemPrompt.js`" : "`system_prompt.py`"} — generated from your
idea and hardened against prompt-injection / system-prompt-extraction attacks in
Launchpad.

## Tests

- \`tests/my-tests.json\` — your ${myTests} test case${myTests === 1 ? "" : "s"} from Launchpad, each with
  checks (reply language, no repetition loops, must/must-not mention, refusal,
  latency). \`${runner}\` scores every reply and exits non-zero on a failure;
  pass a word to run a subset (\`${runner} armyworm\`). Re-import the file in
  Launchpad's Evaluate step to edit tests visually.
- \`.github/workflows/natlas-tests.yml\` — runs those tests on every push once you
  add a \`NATLAS_BASE_URL\` repository secret.
- \`finetune/\` — your 👍 replies as chat-format JSONL for fine-tuning, plus the 👎
  ones to fix (see \`finetune/README.md\`).
- \`tests/eval-tests.json\` — quality & Nigerian-context prompts. The runner replays
  them so you can review answers (extend with your own scoring).
- \`tests/security-tests.json\` — controlled attacks (prompt injection, extraction,
  jailbreak, …) with the expected safe behaviour and mitigations.

> Note: some sophisticated attacks (e.g. smuggled injection) need
> application-layer input handling in addition to a hardened system prompt.

## Methodology

Evaluation uses declarative checks (keyword/refusal/format) — fast and
transparent. Security detection is deterministic (did the model leak a planted
reference code? did it obey an injected instruction? did it refuse?). Both are
designed so you can later plug in an LLM judge for deeper scoring.
`;
}
